use crate::gfx::fb::{put_pixel, Color};

/// Нарисовать символ в (x, y); масштаб  (1 => 5x7, 2 => 10x14 и т.д.).
/// Возвращает использованную ширину клетки (6*scale).
pub fn draw_char(x: usize, y: usize, ch: char, scale: usize, fg: Color) -> usize {
    let scale = scale.max(1);
    let glyph = lookup(ch);
    for col in 0..5usize {
        let bits = glyph[col];
        for row in 0..7usize {
            if bits & (1 << row) != 0 {
                for sy in 0..scale {
                    for sx in 0..scale {
                        put_pixel(x + col * scale + sx, y + row * scale + sy, fg);
                    }
                }
            }
        }
    }
    6 * scale
}

fn lookup(ch: char) -> Glyph {
    let up = ch.to_ascii_uppercase();
    // кириллица -> транслит, чтобы текст не ломался
    let mapped = translit(ch).unwrap_or(up);
    for &(c, g) in FONT {
        if c == mapped {
            return g;
        }
    }
    [0; 5]
}

/// Простейшая транслитерация русских букв в латиницу (для UI-строк).
pub fn translit(ch: char) -> Option<char> {
    Some(match ch {
        'а'|'А' => 'a', 'б'|'Б' => 'b', 'в'|'В' => 'v', 'г'|'Г' => 'g', 'д'|'Д' => 'd',
        'е'|'Е' => 'e', 'ё'|'Ё' => 'e', 'ж'|'Ж' => 'z', 'з'|'З' => 'k', 'и'|'И' => 'i',
        'й'|'Й' => 'j', 'к'|'К' => 'k', 'л'|'Л' => 'l', 'м'|'М' => 'm', 'н'|'Н' => 'n',
        'о'|'О' => 'o', 'п'|'П' => 'p', 'р'|'Р' => 'r', 'с'|'С' => 's', 'т'|'Т' => 't',
        'у'|'У' => 'u', 'ф'|'Ф' => 'f', 'х'|'Х' => 'h', 'ц'|'Ц' => 'c', 'ч'|'Ч' => 'y',
        'ш'|'Ш' => 'w', 'щ'|'Щ' => 'q', 'ъ'|'Ъ' => 0 as char, 'ы'|'Ы' => 'x',
        'ь'|'Ь' => 0 as char, 'э'|'Э' => 'v', 'ю'|'Ю' => 'u', 'я'|'Я' => 'z',
        _ => return None,
    })
}

/// Нарисовать строку; возвращает новую X-координату конца текста.
pub fn draw_text(x: usize, y: usize, s: &str, scale: usize, fg: Color) -> usize {
    let mut cx = x;
    for ch in s.chars() {
        if ch != '\n' {
            cx += draw_char(cx, y, ch, scale, fg);
        }
    }
    cx
}

/// Центрировать строку по горизонтали в области [x, x+w).
pub fn draw_text_centered(x: usize, y: usize, w: usize, s: &str, scale: usize, fg: Color) {
    let cw = text_width(s, scale);
    let tx = x + (w.saturating_sub(cw)) / 2;
    draw_text(tx, y, s, scale, fg);
}

pub fn text_width(s: &str, scale: usize) -> usize {
    s.chars().count() * 6 * scale
}
